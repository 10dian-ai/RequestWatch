const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.RW_PLAYWRIGHT_MODULE || 'playwright-core');

// Real browser regression with deterministic API faults and delayed snapshots.
// A record list's 240-character preview must never masquerade as full content.
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.RW_BROWSER_PATH ? { executablePath: process.env.RW_BROWSER_PATH } : {}) });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
    const errors = []; page.on('pageerror', error => errors.push(String(error)));
    await page.addInitScript(() => sessionStorage.setItem('requestwatch-token', 'packet-test-token'));
    const now = Date.now() / 1000;
    const raw = 'c9\r\ndata: {"choices":[{"delta":{"reasoning_content":"灰色"}}]}\r\n\r\n' + Array.from({ length: 300 }, (_, n) => `完整载荷第${n}行\n`).join('') + 'PACKET-CONTENT-END';
    const tcp = { id: 'packet-stream', source: 'packet', protocol: 'TCP', state: 'captured', created_at: now, src_ip: '172.19.0.2', src_port: 3000, dst_ip: '203.0.113.50', dst_port: 54779, payload_size: Buffer.byteLength(raw), payload_hex: Buffer.from(raw).toString('hex'), payload_text: raw.slice(0, 240), tcp_session_id: 'connection-1', tcp_session_available: true, tcp_session_direction: 'server' };
    const ack = { ...tcp, id: 'packet-ack', payload_hex: '', payload_text: '', payload_size: 0 };
    const expired = { ...tcp, id: 'packet-expired', tcp_session_available: false, tcp_session_unavailable_reason: '关联会话已淘汰，请重新采集。' };
    let streamVersion = 0; let passiveDropped = 0;
    const streamText = () => streamVersion ? 'data: {"choices":[{"delta":{"content":"已经到达的正文"}}]}\n\n' + (streamVersion > 1 ? 'data: [DONE]\n\nSTREAM-CONTENT-END' : '') : '';
    const http = () => ({ id: 'http-stream', source: 'http', protocol: 'HTTP', state: 'forwarded', created_at: now, method: 'GET', url: 'http://example.test/stream', request_body_size: 0, request_body_ref: 'request-empty', request_body_complete: true, request_headers: [], response_headers: [['Content-Type', 'text/event-stream']], status_code: 200, response_body_ref: `stream-${streamVersion}`, response_body_size: Buffer.byteLength(streamText()), response_streaming: streamVersion < 2, response_body_complete: streamVersion === 2 });
    const records = () => [tcp, ack, expired, http()];
    let packetFault = true; let holdDetail = true; let delayDetail;
    const gate = () => new Promise(resolve => { delayDetail = resolve; });
    const direction = { byte_count: raw.length, segment_count: 3, gap_count: 0, missing_bytes: 0 };
    const session = { id: 'connection-1', state: 'open', created_at: now, updated_at: now, midstream: false, complete: false, client_ip: tcp.dst_ip, client_port: tcp.dst_port, server_ip: tcp.src_ip, server_port: tcp.src_port, directions: { client: direction, server: direction } };
    await page.route('http://requestwatch.test/**', async route => {
      const url = new URL(route.request().url()); const resource = url.pathname;
      const json = value => route.fulfill({ contentType: 'application/json', body: JSON.stringify(value) });
      const text = value => route.fulfill({ contentType: 'text/plain; charset=utf-8', body: value });
      if (!resource.startsWith('/api/')) {
        const file = resource === '/' ? 'index.html' : resource.slice(1);
        if (!['index.html', 'app.js', 'app.css', 'favicon.svg'].includes(file)) return route.fulfill({ status: 404 });
        return route.fulfill({ contentType: file.endsWith('.js') ? 'text/javascript' : file.endsWith('.css') ? 'text/css' : file.endsWith('.svg') ? 'image/svg+xml' : 'text/html', body: fs.readFileSync(path.join(__dirname, '..', 'requestwatch', 'static', file)) });
      }
      assert.equal(route.request().headers().authorization, 'Bearer packet-test-token');
      if (resource === '/api/status') return json({ mode: 'live', port: 7030, capture: { passive_dropped: passiveDropped }, stats: { total: 4, packets: 3, http: 1, pending: 0 } });
      if (resource === '/api/containers') return json({ items: [] });
      if (resource === '/api/records') return json({ total: 4, items: records().map(item => { const copy = { ...item }; delete copy.payload_hex; return copy; }) });
      if (resource === '/api/records/packet-stream') {
        if (packetFault) return route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ detail: '测试读取失败' }) });
        if (holdDetail) { holdDetail = false; await gate(); } return json(tcp);
      }
      if (resource === '/api/records/packet-ack') return json(ack);
      if (resource === '/api/records/packet-expired') return json(expired);
      if (resource === '/api/records/http-stream') return json(http());
      if (resource === '/api/sessions') return json({ total: 1, items: [session] });
      if (resource === '/api/sessions/connection-1') return json(session);
      if (resource.includes('/readable/') && !resource.endsWith('/content')) return json({ recognized: true, kind: 'sse', complete: streamVersion === 2, warnings: [], content_url: `${resource}/content?revision=${streamVersion}`, download_url: `${resource}/content?revision=${streamVersion}&download=true`, content_size: Buffer.byteLength(streamText()) });
      if (resource.endsWith('/content')) return text(resource.startsWith('/api/sessions/') ? `${resource.includes('/server/') ? 'SERVER' : 'CLIENT'}-SESSION-CONTENT-END` : resource.includes('/request/') ? '' : streamVersion ? `已经到达的正文${streamVersion > 1 ? '\nSTREAM-CONTENT-END' : ''}` : '');
      if (resource.includes('/body/')) return text(resource.endsWith('/request') ? '' : streamText());
      return route.fulfill({ status: 404, body: resource });
    });
    await page.goto('http://requestwatch.test');
    await page.locator('#records-body tr').first().waitFor();
    await page.locator('#poll-button').click();
    await page.locator('#records-body tr[data-id="packet-stream"]').click();
    await page.locator('[data-tab="request"]').click();
    await page.locator('#detail-retry').waitFor();
    assert.match(await page.locator('#detail-alert').textContent(), /详情加载失败.*测试读取失败/);
    assert.doesNotMatch(await page.locator('#detail-alert').textContent(), /正在.*读取|正在加载/);
    assert.equal(await page.locator('#detail-body pre').count(), 0, 'failed detail must not show 240-character preview as packet body');
    await page.locator('[data-tab="hex"]').click();
    assert.match(await page.locator('#detail-alert').textContent(), /详情加载失败/);
    assert.equal(await page.locator('#detail-body pre').count(), 0);
    packetFault = false;
    await page.locator('#detail-retry').click();
    await page.waitForFunction(() => document.querySelector('#detail-alert').textContent.includes('正在读取此条记录'));
    await page.locator('[data-tab="request"]').click();
    assert.equal(await page.locator('#detail-body pre').count(), 0, 'delayed details must not render summary');
    delayDetail();
    await page.waitForFunction(() => document.querySelector('#detail-body .packet-full-body')?.textContent.endsWith('PACKET-CONTENT-END'));
    assert.equal(await page.locator('#detail-body .packet-full-body').textContent(), raw);
    assert.equal(await page.locator('#detail-alert').isVisible(), false, 'successful detail must clear loading banner');
    assert.equal(await page.locator('#detail-retry').isVisible(), false);
    packetFault = true; passiveDropped = 17;
    await page.locator('#refresh-button').click();
    await page.waitForFunction(() => document.querySelector('#detail-alert').textContent.includes('详情更新失败'));
    assert.equal(await page.locator('#detail-body .packet-full-body').textContent(), raw, 'refresh failure retains last successful body');
    assert.match(await page.locator('#capture-loss-alert').textContent(), /丢弃 17 个包/);
    packetFault = false;
    await page.locator('#detail-retry').click();
    await page.waitForFunction(() => document.querySelector('#detail-alert').hidden);
    assert.equal(await page.locator('[data-tab="request"]').textContent(), '单包载荷');
    assert.match(await page.locator('#packet-context').textContent(), /一条 TCP 包.*一小段/);
    fs.mkdirSync(path.join(__dirname, '..', 'artifacts'), { recursive: true });
    await page.locator('#toast').evaluate(node => { node.hidden = true; });
    await page.locator('aside.detail-panel').first().screenshot({ path: path.join(__dirname, '..', 'artifacts', 'webui-packet-audit.png'), animations: 'disabled' });
    await page.locator('#packet-context .session-link').click();
    await page.waitForFunction(() => document.querySelector('#session-content .readable-body')?.textContent === 'SERVER-SESSION-CONTENT-END');
    assert.equal(await page.locator('[data-session-side="server"]').getAttribute('aria-selected'), 'true');
    await page.locator('.navigation [data-view="traffic"]').click();
    if (delayDetail) delayDetail();
    await page.locator('[data-tab="response"]').click();
    await page.locator('#detail-body .session-link').click();
    await page.waitForFunction(() => document.querySelector('#session-content .readable-body')?.textContent === 'CLIENT-SESSION-CONTENT-END');
    await page.locator('.navigation [data-view="traffic"]').click();
    if (delayDetail) delayDetail();
    await page.locator('#records-body tr[data-id="packet-ack"]').click();
    await page.locator('[data-tab="request"]').click();
    await page.waitForFunction(() => document.querySelector('#detail-body').textContent.includes('此包没有应用载荷'));
    assert.equal(await page.locator('#packet-context .session-link').count(), 1);
    await page.locator('#records-body tr[data-id="packet-expired"]').click();
    await page.waitForFunction(() => document.querySelector('#packet-context').textContent.includes('关联会话已淘汰'));
    assert.equal(await page.locator('#packet-context .session-link').count(), 0);
    await page.locator('#records-body tr[data-id="http-stream"]').click();
    await page.locator('[data-tab="response"]').click();
    await page.waitForFunction(() => document.querySelector('#detail-body').textContent.includes('正在等待第一段响应正文'));
    assert.match(await page.locator('#detail-alert').textContent(), /流式响应仍在接收/);
    assert.doesNotMatch(await page.locator('#detail-alert').textContent(), /无法补回|重新抓取/);
    streamVersion = 1;
    await page.locator('#refresh-button').click();
    await page.waitForFunction(() => document.querySelector('#detail-body .readable-body')?.textContent === '已经到达的正文');
    assert.match(await page.locator('#detail-body .body-status').textContent(), /流式响应进行中/);
    await page.locator('#http-body-format').selectOption('text');
    await page.waitForFunction(raw => document.querySelector('#detail-body .full-body')?.textContent === raw, streamText());
    streamVersion = 2;
    await page.locator('#refresh-button').click();
    await page.waitForFunction(() => document.querySelector('#detail-body .full-body')?.textContent.endsWith('STREAM-CONTENT-END'));
    assert.match(await page.locator('#detail-body .body-status').textContent(), /完整保存/);
    assert.equal(await page.locator('#detail-alert').isVisible(), false);
    await page.locator('#http-body-format').selectOption('auto');
    await page.waitForFunction(() => document.querySelector('#detail-body .readable-body')?.textContent.endsWith('STREAM-CONTENT-END'));
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1), false);
    assert.deepEqual(errors, []);
    console.log('Packet details UI passed: failed/delayed details cannot show truncated list preview; retry and loading state; full payload bytes; correct TCP direction links; ACK and evicted sessions; live SSE empty/partial/complete transitions in auto and original views.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
