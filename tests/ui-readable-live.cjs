const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.RW_PLAYWRIGHT_MODULE || 'playwright-core');
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.RW_BROWSER_PATH ? { executablePath: process.env.RW_BROWSER_PATH } : {}) });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
    const errors = []; page.on('pageerror', error => errors.push(String(error)));
    const base = process.env.RW_UI_URL || 'http://127.0.0.1:7030';
    const token = process.env.RW_UI_TOKEN || 'requestwatch-local-demo-7030';
    const headers = { Authorization: `Bearer ${token}` };
    await page.addInitScript(value => sessionStorage.setItem('requestwatch-token', value), token);
    const before = await (await page.request.get(`${base}/api/status`, { headers })).json();
    assert.equal(before.mode, 'demo', 'Run fixture injection only against an isolated demo server.');
    const marker = `readable-live-${Date.now()}`;
    const request = JSON.stringify({ messages: [{ role: 'user', content: '请用中文回答。\n保留完整内容。' }], stream: true });
    const parts = ['这是第一行。\n', '这是第二行，', '会按顺序合并。\n', marker];
    const response = parts.map((content, index) => `data: ${JSON.stringify({ id: marker, choices: [{ index: 0, delta: { ...(index === 0 ? { role: 'assistant' } : {}), content } }] })}\n\n`).join('') + 'data: [DONE]\n\n';
    const inserted = await page.request.post(`${base}/api/internal/ingest`, { headers, data: { source: 'http', protocol: 'HTTP', method: 'POST', url: `http://fixture.invalid/${marker}`, request_headers: [['Content-Type', 'application/json']], request_body_text: request, request_body_size: Buffer.byteLength(request), src_ip: '127.0.0.1', src_port: 45000, dst_ip: '127.0.0.1', dst_port: 80 } });
    assert(inserted.ok(), await inserted.text());
    const id = (await inserted.json()).id;
    const afterInsert = await (await page.request.get(`${base}/api/status`, { headers })).json();
    assert.equal(afterInsert.stats.captured_total, before.stats.captured_total + 1);
    const updated = await page.request.put(`${base}/api/internal/records/${id}`, { headers, data: { state: 'forwarded', status_code: 200, response_headers: [['Content-Type', 'text/event-stream; charset=utf-8']], response_body_text: response, response_body_size: Buffer.byteLength(response) } });
    assert(updated.ok(), await updated.text());
    const afterResponse = await (await page.request.get(`${base}/api/status`, { headers })).json();
    assert.equal(afterResponse.stats.captured_total, afterInsert.stats.captured_total, 'response updates are not new captures');
    const metaResponse = await page.request.get(`${base}/api/records/${id}/readable/response`, { headers });
    assert(metaResponse.ok(), await metaResponse.text());
    const meta = await metaResponse.json();
    assert.equal(meta.recognized, true);
    const parsedText = await (await page.request.get(`${base}${meta.content_url}`, { headers })).text();
    assert(parsedText.includes(parts.join('')), parsedText);
    await page.goto(base);
    await page.locator('#filter-query').fill(marker);
    await page.locator(`#records-body tr[data-id="${id}"]`).waitFor();
    await page.locator(`#records-body tr[data-id="${id}"]`).click();
    await page.locator('[data-tab="response"]').click();
    await page.locator('#detail-body .readable-body').waitFor();
    assert.equal(await page.locator('#detail-body .readable-body').textContent(), parsedText);
    assert.equal(await page.locator('#stat-total').textContent(), afterResponse.stats.captured_total.toLocaleString('zh-CN'));
    const [download] = await Promise.all([page.waitForEvent('download'), page.locator('#body-download').click()]);
    assert(fs.readFileSync(await download.path()).equals(Buffer.from(response)), 'raw SSE download must be byte-identical');
    await page.locator('#http-body-format').selectOption('text');
    await page.waitForFunction(raw => document.querySelector('#detail-body .full-body')?.textContent === raw, response);
    await page.locator('#http-body-format').selectOption('auto');
    await page.locator('#detail-body .readable-body').waitFor();
    fs.mkdirSync(path.join(__dirname, '..', 'artifacts'), { recursive: true });
    await page.locator('#view-traffic .detail-panel').screenshot({ path: path.join(__dirname, '..', 'artifacts', 'webui-http-readable-real.png') });
    if (process.env.RW_UI_READABLE_SESSION_ID) {
      const sessionId = process.env.RW_UI_READABLE_SESSION_ID;
      const sessionMarker = process.env.RW_UI_READABLE_SESSION_MARKER || 'TCP-READABLE-END';
      await page.locator('.navigation [data-view="sessions"]').click();
      await page.locator('#session-query').fill(sessionMarker);
      await page.locator(`#sessions-body tr[data-id="${sessionId}"]`).waitFor();
      await page.locator(`#sessions-body tr[data-id="${sessionId}"]`).click();
      await page.locator('#session-content .readable-body').waitFor();
      const sessionMeta = await (await page.request.get(`${base}/api/sessions/${sessionId}/readable/client`, { headers })).json();
      assert.equal(sessionMeta.recognized, true);
      const sessionText = await (await page.request.get(`${base}${sessionMeta.content_url}`, { headers })).text();
      assert.equal(await page.locator('#session-content .readable-body').textContent(), sessionText);
      assert(sessionText.includes('这是合并后的第一行。\n第二行的内容也会接在后面。\nTCP-READABLE-END'));
      assert.match(await page.locator('[data-session-side="client"]').textContent(), /端点 A → B（方向推测）/);
      const original = await (await page.request.get(`${base}/api/sessions/${sessionId}/body/client?view=raw`, { headers })).body();
      const [rawTcp] = await Promise.all([page.waitForEvent('download'), page.locator('#session-download-raw').click()]);
      assert(fs.readFileSync(await rawTcp.path()).equals(original));
      await page.locator('.session-detail').screenshot({ path: path.join(__dirname, '..', 'artifacts', 'webui-tcp-readable-real.png') });
      await page.locator('#session-format').selectOption('text');
      await page.waitForFunction(raw => document.querySelector('#session-content .session-full-body')?.textContent === raw, original.toString());
      await page.locator('#session-format').selectOption('auto');
      await page.locator('#session-content .readable-body').waitFor();
      await page.setViewportSize({ width: 390, height: 844 });
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1), false);
      await page.locator('.session-detail').screenshot({ path: path.join(__dirname, '..', 'artifacts', 'webui-tcp-readable-real-mobile.png') });
    }
    assert.deepEqual(errors, []);
    console.log(`Real readable UI passed: cumulative capture/update counts, HTTP SSE Chinese chunks merged, byte-exact original download, raw/parsed switching${process.env.RW_UI_READABLE_SESSION_ID ? ', real TCP chunk framing removal / inferred direction / complete raw download / mobile layout' : ''}.`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
